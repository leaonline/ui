const template = 'sortItemRenderer'
describe(template, () => {
  describe('default state', () => {
    it('renders lists of draggables and dropzones')
  })
  describe('interaction', () => {
    it('renders a connection if draggable is dropped on the dropzone')
    it('erases a connection if the cancenl button is clicked')
  })
  describe('scoring', () => {
    it('renders a successful connection if correct')
    it('renders a failed connection if wrong')
    it('renders an expected connection')
    it('renders an explanation if given')
  })
})
